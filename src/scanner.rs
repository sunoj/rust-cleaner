/// Phase 1: discover artifact directories (fast, <1s).
pub fn scan_discover(config: &Config) -> Vec<TargetDir> {
    let types: Vec<&str> = config.artifact_types.iter().map(|s| s.as_str()).collect();
    let dirs: Vec<&PathBuf> = config.scan_dirs.iter().filter(|d| d.exists()).collect();
    let mut found: Vec<TargetDir> = std::thread::scope(|s| {
        let handles: Vec<_> = dirs
            .iter()
            .map(|dir| {
                let types = &types;
                let artifact_types = &config.artifact_types;
                let max_depth = config.max_depth;
                s.spawn(move || {
                    let mut local = Vec::new();
                    let walker = WalkDir::new(dir).max_depth(max_depth);
                    for entry in walker
                        .into_iter()
                        .filter_entry(|e| !should_skip(e, artifact_types))
                        .filter_map(Result::ok)
                    {
                        if entry.depth() == 0 || !entry.file_type().is_dir() {
                            continue;
                        }
                        let name = entry.file_name().to_string_lossy();
                        if !types.iter().any(|t| *t == name) {
                            continue;
                        }
                        if !is_dev_artifact(entry.path(), &name) {
                            continue;
                        }
                        let last_modified = entry
                            .metadata()
                            .ok()
                            .and_then(|m| m.modified().ok())
                            .unwrap_or(SystemTime::UNIX_EPOCH);
                        let kind = match name.as_ref() {
                            "target" => ArtifactKind::RustTarget,
                            "node_modules" => ArtifactKind::NodeModules,
                            _ => ArtifactKind::BuildOutput,
                        };
                        local.push(TargetDir {
                            path: entry.into_path(),
                            size_bytes: 0,
                            last_modified,
                            kind,
                        });
                    }
                    local
                })
            })
            .collect();
        handles
            .into_iter()
            .flat_map(|h| h.join().unwrap_or_default())
            .collect()
    });
    collect_tmp_targets(&mut found);
    collect_shared_cargo_target(&mut found);
    collect_aid_worktrees(&mut found);
    collect_dev_caches(&mut found);
    found
}

/// Phase 2: compute sizes in parallel for already-discovered targets.
pub fn scan_sizes(targets: &mut Vec<TargetDir>) {
    let paths: Vec<&Path> = targets.iter().map(|td| td.path.as_path()).collect();
    let sizes: Vec<u64> = std::thread::scope(|s| {
        let handles: Vec<_> = paths
            .iter()
            .map(|p| s.spawn(|| dir_size(p)))
            .collect();
        handles
            .into_iter()
            .map(|h| h.join().unwrap_or(0))
            .collect()
    });
    for (td, size) in targets.iter_mut().zip(sizes) {
        td.size_bytes = size;
    }
    subtract_nested_sizes(targets);
    targets.sort_by(|a, b| b.size_bytes.cmp(&a.size_bytes));
}

/// When one target is an ancestor of another (e.g. ~/.cargo-target/smart-router
/// and ~/.cargo-target/smart-router/session-a), subtract the descendant's size
/// from the ancestor so the total across all targets reflects disk usage.
fn subtract_nested_sizes(targets: &mut [TargetDir]) {
    let entries: Vec<(PathBuf, u64)> = targets
        .iter()
        .map(|t| (t.path.clone(), t.size_bytes))
        .collect();
    for target in targets.iter_mut() {
        for (path, size) in &entries {
            if path == &target.path {
                continue;
            }
            if path.starts_with(&target.path) {
                target.size_bytes = target.size_bytes.saturating_sub(*size);
            }
        }
    }
}

/// Directories that never contain dev artifacts — skip to avoid slow traversal.
const SKIP_DIRS: &[&str] = &[
    // Media & personal
    "Music", "Movies", "Photos", "Pictures",
    // macOS system
    "Library", "Applications", "System",
    // iCloud & cloud storage
    "Mobile Documents", "iCloud Drive", "Google Drive", "OneDrive", "Dropbox",
    // Network & external volumes
    "Volumes",
];

fn should_skip(entry: &DirEntry, artifact_types: &[String]) -> bool {
    if entry.depth() == 0 || !entry.file_type().is_dir() {
        return false;
    }
    // Skip symlinks — don't follow into network mounts or iCloud aliases
    if entry.path_is_symlink() {
        return true;
    }
    let name = entry.file_name().to_string_lossy();
    // Skip hidden dirs (except known artifact types like .next)
    if name.starts_with('.') && !artifact_types.iter().any(|t| t == name.as_ref()) {
        return true;
    }
    // Skip non-dev directories (media, cloud, system)
    if SKIP_DIRS.iter().any(|&s| s == name.as_ref()) {
        return true;
    }
    // Don't descend INTO artifact directories — we only need the dir itself, not its children.
    if let Some(parent_name) = entry.path().parent().and_then(|p| p.file_name()) {
        let pname = parent_name.to_string_lossy();
        if artifact_types.iter().any(|t| t == pname.as_ref()) {
            return true;
        }
    }
    false
}

/// Validate that a directory is actually a dev artifact, not a false positive.
fn is_dev_artifact(path: &Path, name: &str) -> bool {
    match name {
        "target" => path.join("debug").is_dir() || path.join("release").is_dir(),
        "node_modules" => {
            path.parent().is_some_and(|parent| parent.join("package.json").is_file())
                || path.join(".package-lock.json").is_file()
                || path.join(".yarn-integrity").is_file()
                || path.join(".modules.yaml").is_file()
                || path.join(".pnpm").is_dir()
                || path.join(".bin").is_dir()
        }
        ".next" => path.join("cache").is_dir() || path.join("static").is_dir(),
        "dist" | "build" => path.parent().is_some_and(|p| {
            p.join("package.json").is_file()
                || p.join("Cargo.toml").is_file()
                || p.join("build.gradle").is_file()
                || p.join("platformio.ini").is_file()
        }),
        _ => false,
    }
}

/// Collect /tmp Cargo target dirs (no size computation).
///
/// Recognized name patterns (all confirmed by a `debug/` or `release/` subdir):
///   * `cc-target-*`               — Claude Code per-session targets
///   * `*-target`                  — ad-hoc CARGO_TARGET_DIR (e.g. `smart-router-target`)
///   * `*-target-*`                — ad-hoc CARGO_TARGET_DIR with suffix (e.g. `fusion-filler-target-issue144`)
fn collect_tmp_targets(found: &mut Vec<TargetDir>) {
    // macOS: /tmp is a symlink to /private/tmp. read_dir on either works.
    let tmp = Path::new("/tmp");
    let entries = match std::fs::read_dir(tmp) {
        Ok(e) => e,
        Err(_) => return,
    };
    for entry in entries.filter_map(Result::ok) {
        let name = entry.file_name();
        let name_str = name.to_string_lossy();
        if !is_tmp_target_name(&name_str) {
            continue;
        }
        let path = entry.path();
        if path.is_symlink() || !path.is_dir() {
            continue;
        }
        // Validate it's actually a cargo target dir, not an unrelated dir that
        // happens to contain "-target" in the name.
        if !path.join("debug").is_dir() && !path.join("release").is_dir() {
            continue;
        }
        let last_modified = entry
            .metadata()
            .ok()
            .and_then(|m| m.modified().ok())
            .unwrap_or(SystemTime::UNIX_EPOCH);
        found.push(TargetDir {
            path,
            size_bytes: 0,
            last_modified,
            kind: ArtifactKind::TmpTarget,
        });
    }
}

fn is_tmp_target_name(name: &str) -> bool {
    name.starts_with("cc-target-")
        || name.ends_with("-target")
        || name.contains("-target-")
}

/// Collect ~/.aid/worktrees/<repo>/<branch>/target directories.
/// These live under a dot-prefixed dir so the main WalkDir skips them.
fn collect_aid_worktrees(found: &mut Vec<TargetDir>) {
    let Some(home) = dirs::home_dir() else { return };
    let root = home.join(".aid").join("worktrees");
    let Ok(repos) = std::fs::read_dir(&root) else { return };
    for repo in repos.filter_map(Result::ok) {
        let repo_path = repo.path();
        if repo_path.is_symlink() || !repo_path.is_dir() {
            continue;
        }
        let Ok(branches) = std::fs::read_dir(&repo_path) else { continue };
        for branch in branches.filter_map(Result::ok) {
            let branch_path = branch.path();
            if branch_path.is_symlink() || !branch_path.is_dir() {
                continue;
            }
            let target = branch_path.join("target");
            if !target.is_dir() {
                continue;
            }
            if !target.join("debug").is_dir() && !target.join("release").is_dir() {
                continue;
            }
            let last_modified = std::fs::metadata(&target)
                .ok()
                .and_then(|m| m.modified().ok())
                .unwrap_or(SystemTime::UNIX_EPOCH);
            found.push(TargetDir {
                path: target,
                size_bytes: 0,
                last_modified,
                kind: ArtifactKind::RustTarget,
            });
        }
    }
}

fn collect_dev_caches(found: &mut Vec<TargetDir>) {
    let Some(home) = dirs::home_dir() else { return };
    for path in [
        home.join("Library/Developer/Xcode/DerivedData"),
        home.join("Library/Developer/Xcode/ModuleCache.noindex"),
        home.join("Library/Caches/Homebrew"),
        home.join(".npm"),
        home.join(".cache/pnpm"),
        home.join(".local/share/pnpm/store"),
        home.join(".cache/yarn"),
        home.join(".config/yarn"),
        home.join(".pnpm-store"),
        PathBuf::from("/opt/homebrew/var/homebrew/cache"),
        PathBuf::from("/usr/local/var/homebrew/cache"),
    ] {
        push_known_dir(found, path, ArtifactKind::Cache);
    }

    let devices_root = home.join("Library/Developer/CoreSimulator/Devices");
    let Ok(devices) = std::fs::read_dir(&devices_root) else { return };
    for device in devices.filter_map(Result::ok) {
        let path = device.path().join("data/Library/Caches");
        push_known_dir(found, path, ArtifactKind::Cache);
    }
}

/// Collect per-project subdirs under ~/.cargo-target/ (shared CARGO_TARGET_DIR root).
/// Supports both <project>/debug and <project>/<session>/debug layouts.
fn collect_shared_cargo_target(found: &mut Vec<TargetDir>) {
    let Some(home) = dirs::home_dir() else { return };
    let root = home.join(".cargo-target");
    let entries = match std::fs::read_dir(&root) {
        Ok(e) => e,
        Err(_) => return,
    };
    for entry in entries.filter_map(Result::ok) {
        let path = entry.path();
        if path.is_symlink() || !path.is_dir() {
            continue;
        }
        try_push_cargo_target(found, &path);
        let Ok(subs) = std::fs::read_dir(&path) else { continue };
        for sub in subs.filter_map(Result::ok) {
            let sub_path = sub.path();
            if sub_path.is_symlink() || !sub_path.is_dir() {
                continue;
            }
            try_push_cargo_target(found, &sub_path);
        }
    }
}

fn try_push_cargo_target(found: &mut Vec<TargetDir>, path: &Path) -> bool {
    if !path.join("debug").is_dir() && !path.join("release").is_dir() {
        return false;
    }
    let last_modified = std::fs::metadata(path)
        .ok()
        .and_then(|m| m.modified().ok())
        .unwrap_or(SystemTime::UNIX_EPOCH);
    found.push(TargetDir {
        path: path.to_path_buf(),
        size_bytes: 0,
        last_modified,
        kind: ArtifactKind::RustTarget,
    });
    true
}

fn push_known_dir(found: &mut Vec<TargetDir>, path: PathBuf, kind: ArtifactKind) {
    if path.is_symlink() || !path.is_dir() {
        return;
    }
    let last_modified = std::fs::metadata(&path)
        .ok()
        .and_then(|m| m.modified().ok())
        .unwrap_or(SystemTime::UNIX_EPOCH);
    found.push(TargetDir {
        path,
        size_bytes: 0,
        last_modified,
        kind,
    });
}

/// Compute directory size using macOS getattrlistbulk for bulk metadata reads.
/// Falls back to walkdir+stat if the bulk API fails.
fn dir_size(path: &Path) -> u64 {
    let limit = disk_space(path).map(|stats| stats.total_bytes);
    match dir_size_bulk(path) {
        Some(size) if size_within_limit(size, limit) => size,
        _ => clamp_size(dir_size_fallback(path), limit),
    }
}

const BULK_ATTRS: RequestedAttributes = RequestedAttributes {
    name: true,
    object_type: true,
    size: true,
    alloc_size: true,
    modified_time: false,
    permissions: false,
    inode: false,
    entry_count: false,
};
const BULK_BUF: usize = 256 * 1024;

fn dir_size_bulk(path: &Path) -> Option<u64> {
    let mut total: u64 = 0;
    let mut dirs = vec![path.to_path_buf()];
    while let Some(dir) = dirs.pop() {
        let entries = DirReader::new(&dir)
            .attributes(BULK_ATTRS)
            .buffer_size(BULK_BUF)
            .follow_symlinks(false)
            .read()
            .ok()?;
        for result in entries {
            let entry = match result {
                Ok(e) => e,
                Err(_) => return None, // parse error — data may be corrupt, fall back
            };
            match entry.object_type {
                Some(ObjectType::Directory) => dirs.push(dir.join(&entry.name)),
                Some(ObjectType::Symlink) => {}
                _ => {
                    let bytes = entry.alloc_size.or(entry.size).unwrap_or(0);
                    total = total.saturating_add(bytes);
                }
            }
        }
    }
    Some(total)
}

fn dir_size_fallback(path: &Path) -> u64 {
    WalkDir::new(path)
        .follow_links(false)
        .into_iter()
        .filter_map(Result::ok)
        .filter_map(|entry| entry.metadata().ok())
        .map(|meta| meta.blocks().saturating_mul(512))
        .fold(0_u64, |total, size| total.saturating_add(size))
}

fn size_within_limit(size: u64, limit: Option<u64>) -> bool {
    match limit {
        Some(max_size) => size <= max_size,
        None => true,
    }
}

fn clamp_size(size: u64, limit: Option<u64>) -> u64 {
    match limit {
        Some(max_size) => size.min(max_size),
        None => size,
    }
}

pub fn human_size(bytes: u64) -> String {
    let mut value = bytes as f64;
    let mut unit = 0;
    let units = ["B", "K", "M", "G", "T"];
    while value >= 1024.0 && unit < units.len() - 1 {
        value /= 1024.0;
        unit += 1;
    }
    if unit == 0 {
        format!("{}{}", bytes, units[unit])
    } else {
        format!("{:.1}{}", value, units[unit])
    }
}

#[cfg(test)]
mod overlap_tests {
    use super::sizes_may_overlap;
    use std::path::PathBuf;

    #[test]
    fn shared_cargo_root_targets_can_overlap() {
        let paths = vec![PathBuf::from("/Users/x/.cargo-target/proj/session-a")];
        assert!(sizes_may_overlap(&paths));
    }

    #[test]
    fn ordinary_project_targets_do_not_overlap() {
        let paths = vec![
            PathBuf::from("/Users/x/Develop/proj/target"),
            PathBuf::from("/Users/x/Develop/web/node_modules"),
        ];
        assert!(!sizes_may_overlap(&paths));
    }
}

#[cfg(test)]
mod artifact_tests {
    use super::is_dev_artifact;
    use std::fs;
    use std::path::PathBuf;
    use std::time::{SystemTime, UNIX_EPOCH};

    fn temp_dir(name: &str) -> PathBuf {
        let mut path = std::env::temp_dir();
        let stamp = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|d| d.as_nanos())
            .unwrap_or(0);
        path.push(format!("wd40-{name}-{}-{stamp}", std::process::id()));
        path
    }

    fn cleanup(path: &PathBuf) {
        let _ = fs::remove_dir_all(path);
    }

    #[test]
    fn pnpm_markers_allow_node_modules_detection() {
        let root = temp_dir("pnpm-markers");
        let node_modules = root.join("node_modules");
        let marker = node_modules.join(".modules.yaml");
        let pnpm = node_modules.join(".pnpm");
        let bin = node_modules.join(".bin");
        let _ = fs::create_dir_all(&pnpm);
        let _ = fs::create_dir_all(&bin);
        let _ = fs::create_dir_all(&node_modules);
        let _ = fs::write(&marker, "hoistPattern: []");

        assert!(is_dev_artifact(&node_modules, "node_modules"));
        cleanup(&root);
    }

    #[test]
    fn node_modules_without_markers_are_ignored() {
        let root = temp_dir("node-modules-empty");
        let node_modules = root.join("node_modules");
        let _ = fs::create_dir_all(&node_modules);

        assert!(!is_dev_artifact(&node_modules, "node_modules"));
        cleanup(&root);
    }
}
